        public static List<spkfk> getList(string lastmodifytime)
        {
            string sql = @"select a.goodsid as spid,a.goodsid as spbh,a.goodsname as spmch,a.opcode as zjm,a.barcode as sptm,
a.GOODSTYPE as shpgg,a.GOODSUNIT as dw,a.FACTORYNAME as shengccj,a.APPROVEDOCNO as pizhwh,a.HOLDERSNAME as ypcyr,
a.SUPPLYTAXRATE*100 as  tj_ylshj 
from wqh_sp a
--where SYS_MODIFYDATE > :lastmodifytime";
            var sp = Oracle.ExecuteDataTable(sql, new OracleParameter[] { new OracleParameter("lastmodifytime", lastmodifytime) });
            return WQH.Convert.TableToList<spkfk>(sp);
        }
